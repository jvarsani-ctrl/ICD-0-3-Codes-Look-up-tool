def carry_branch_sequences(new_trees: list, old_trees: list) -> None:
    """Keep induce_flow.py's branch_sequence where a node's rules did not change."""
    old = {}
    for t in old_trees or []:
        for n in t.get("nodes") or []:
            if n.get("branch_sequence") is not None:
                old[n["node_id"]] = (json.dumps(n.get("resolution_logic"), sort_keys=True),
                                     json.dumps(n.get("marker_groups"), sort_keys=True),
                                     n["branch_sequence"])
    for t in new_trees:
        for n in t.get("nodes") or []:
            if n.get("node_type") != "ihc_checklist":
                continue
            prior = old.get(n["node_id"])
            if prior and prior[0] == json.dumps(n.get("resolution_logic"), sort_keys=True) \
                    and prior[1] == json.dumps(n.get("marker_groups"), sort_keys=True):
                n["branch_sequence"] = prior[2]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=str(OUT_PATH))
    args = ap.parse_args(argv)

    payload = gi.build_inventory(ICCC_PATH, ICDO_PATH, "VIII")
    obs = load_obs(ICDO_PATH)
    entries = [build_entry(r, obs) for r in payload["records"]]

    missing = set(ANNOTATIONS) - {e["morphology_code"] for e in entries}
    if missing:
        print("ERROR: annotated code(s) absent from the generated inventory: %s"
              % ", ".join(sorted(missing)), file=sys.stderr)
        return 2

    if args.check:
        print("usable entries: %d" % len(entries))
        for sub, n in sorted(Counter(e["iccc3_subgroup_id"] for e in entries).items()):
            print("  %s: %d" % (sub, n))
        print("annotated: %d · templated: %d" % (len(ANNOTATIONS), len(entries) - len(ANNOTATIONS)))
        return 0

    out_path = Path(args.out)
    trees = group08_tree.trees()
    if out_path.exists():
        try:
            carry_branch_sequences(trees, json.loads(out_path.read_text(encoding="utf-8"))
                                   .get("decision_trees"))
        except (json.JSONDecodeError, OSError) as exc:
            print("ERROR: %s exists but could not be read (%s); refusing to overwrite it"
                  % (out_path, exc), file=sys.stderr)
            return 2
    doc = {
        "metadata": build_metadata(entries, payload["summary"], trees),
        "morphology_entries": entries,
        "decision_trees": trees,
    }
    out_path.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote %s (%d entries, %d node(s))"
          % (out_path, len(entries), doc["metadata"]["total_decision_nodes"]), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
