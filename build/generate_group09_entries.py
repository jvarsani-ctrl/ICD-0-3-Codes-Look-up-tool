def obs_clause(flags: dict) -> str:
    if flags.get("preferred"):
        return "; the preferred term itself carries the ICD-O-3.2 [obs] marker"
    if flags.get("other"):
        return "; one or more synonym or related terms carry [obs], the preferred term does not"
    return ""


def load_obs_flags(icdo_path: Path) -> dict:
    con = sqlite3.connect("file:%s?mode=ro" % icdo_path, uri=True)
    out: dict = {}
    for code4, beh, level, obs in con.execute(
            "SELECT code4, behaviour, level, obs FROM icd_o_3_2_morphology "
            "WHERE code4 IS NOT NULL AND behaviour IS NOT NULL"):
        slot = out.setdefault((str(code4), str(beh)), {"preferred": False, "other": False})
        if obs:
            slot["preferred" if str(level).strip() == "Preferred" else "other"] = True
    con.close()
    return out


def build_entry(rec: dict, names: dict, obs_flags: dict) -> dict:
    code, beh = rec["morphology_code"], rec["behavior_code"]
    a = ANNOTATIONS[code]
    flags = obs_flags.get((code, beh), {})
    parts = [GENERATED_NOTE,
             "ICD-O-3.2 preferred term %r, behaviour 3%s." % (rec["preferred_term"], obs_clause(flags))]
    if a.get("who"):
        parts.append("WHO 2020 entity on this stem: %s, per %s." % (a["who"], SBARAGLIA))
    else:
        parts.append("No WHO 2020 soft tissue entity lives on this stem (%s)." % SBARAGLIA)
    if a.get("paed"):
        parts.append("Paediatric occurrence: %s (%s)." % (a["paed"], PFISTER))
    parts.append("Reached by the g9_soft_tissue tree." if a["leaf"]
                 else "No decision-tree leaf; reachable by direct code entry only (contract §1).")
    if a.get("note"):
        parts.append(a["note"])
    nos = a.get("nos")
    entry = {
        "morphology_code": code,
        "morphology_name": rec["preferred_term"],
        "iccc3_subgroup_id": rec["iccc3_subgroup_id"],
        "iccc3_subgroup_name": rec["iccc3_subgroup_name"],
        "who_version": "WHO 2020",
        "behavior_code": beh,
        "diagnostic_tests_required": list(a["tests"]),
        "ihc_markers_required": list(a["ihc"]) if a.get("ihc") else None,
        "ihc_markers_exclude": None,
        "imaging_sufficient": False,
        "imaging_features": None,
        "nos_fallback_code": nos,
        "nos_fallback_name": names[nos] if nos else None,
        "clinical_alert": None,
        "coding_note": " ".join(parts),
        "code_neutral_molecular": a.get("neutral", True),
        "redcap_value": code,
        "primary_sites": [t.replace("–", "-") for t in rec["topography"]],
        "topography_dependent": bool(a.get("topo")),
        "topography_routing_note": a.get("topo"),
    }
    return {f: entry[f] for f in FIELD_ORDER}


def build_metadata(n_entries: int, summary: dict, n_nodes: int, tree_ids: list) -> dict:
    return {
        "group_id": 9,
        "group_name": "Soft Tissue and Other Extraosseous Sarcomas",
        "iccc3_version": "3rd edition",
        "icdo_version": (
            "ICD-O-3.2. morphology_entries[] is GENERATED by build/generate_group_inventory.py "
            "--group IX from ICCC-2017.sqlite joined to icdo32.sqlite, run via "
            "build/generate_group09_entries.py (Group 9 build contract §1, §0.3). Generator "
            "summary: ICCC range entries %d, distinct codes %d, absent from ICD-O-3.2 at the "
            "declared behaviour (3) %d, usable %d. 'Absent at the declared behaviour' means "
            "absent at behaviour 3, not absent from ICD-O-3.2: 57 of the REDCap options exist only "
            "at behaviour 0 or 1 and reach behaviour_exclusion branches. Ewing sarcoma is 9364/3, "
            "not 9260/3 (contract §0.5); 9150 is deleted (moved to 8815); 8832/3 is "
            "fibrosarcomatous DFSP only (contract §0.6)."
            % (summary["iccc_code_range_entries"], summary["iccc_distinct_codes"],
               len(summary["codes_absent_from_icdo32"]), summary["usable_distinct_codes"])
        ),
        "total_morphology_entries": n_entries,
        "total_decision_nodes": n_nodes,
        "decision_trees": list(tree_ids),
        "basis_of_diagnosis_declarations": {"ihc_counts_as": 7, "methylation_counts_as": 8},
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=str(OUT_PATH))
    ap.add_argument("--reset-tree", action="store_true")
    args = ap.parse_args(argv)

    iccc = Path(os.environ.get("ICCC_DB", str(gi.DEFAULT_ICCC)))
    icdo = Path(os.environ.get("ICDO_DB", str(gi.DEFAULT_ICDO)))
    payload = gi.build_inventory(iccc, icdo, "IX")
    records = payload["records"]
    codes = {r["morphology_code"] for r in records}

    missing = codes - set(ANNOTATIONS)
    extra = set(ANNOTATIONS) - codes
    if missing or extra:
        print("ERROR: annotation table and generated inventory disagree. Unannotated: %s. "
              "Annotated but not generated: %s." % (sorted(missing), sorted(extra)), file=sys.stderr)
        return 2
    names = {r["morphology_code"]: r["preferred_term"] for r in records}
    for code, a in ANNOTATIONS.items():
        if a.get("nos") and a["nos"] not in names:
            print("ERROR: %s falls back to %s, which is not in the inventory" % (code, a["nos"]),
                  file=sys.stderr)
            return 2

    entries = [build_entry(r, names, load_obs_flags(icdo)) for r in records]
    if args.check:
        print("usable entries: %d" % len(entries))
        for sub, n in sorted(Counter(e["iccc3_subgroup_id"] for e in entries).items()):
            print("  %s: %d" % (sub, n))
        print("tree leaves: %d; direct entry only: %d"
              % (sum(a["leaf"] for a in ANNOTATIONS.values()),
                 sum(not a["leaf"] for a in ANNOTATIONS.values())))
        return 0

    out_path = Path(args.out)
    trees = []
    if out_path.exists() and not args.reset_tree:
        try:
            trees = json.loads(out_path.read_text(encoding="utf-8")).get("decision_trees") or []
        except (json.JSONDecodeError, OSError) as exc:
            print("ERROR: %s exists but could not be read (%s); refusing to overwrite a tree."
                  % (out_path, exc), file=sys.stderr)
            return 2
    n_nodes = sum(len(t.get("nodes") or []) for t in trees)
    out = {
        "metadata": build_metadata(len(entries), payload["summary"], n_nodes,
                                   [t.get("tree_id") for t in trees if t.get("tree_id")]),
        "morphology_entries": entries,
        "decision_trees": trees,
    }
    out_path.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote %s (%d entries, %d tree(s) / %d node(s) carried across)"
          % (out_path, len(entries), len(trees), n_nodes), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
