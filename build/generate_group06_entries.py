def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                     help="print the entry count and subgroup breakdown; write nothing")
    ap.add_argument("--out", default=str(OUT_PATH))
    ap.add_argument("--reset-tree", action="store_true",
                     help="ALSO empty decision_trees[]. Without this the existing tree is "
                          "carried across unchanged; this script generates entries, and "
                          "silently deleting a tree someone else authored is the one thing "
                          "a regeneration step must never do.")
    args = ap.parse_args(argv)

    payload = gi.build_inventory(gi.DEFAULT_ICCC, gi.DEFAULT_ICDO, "VI")
    records = payload["records"]
    obs_flags = load_obs_flags(gi.DEFAULT_ICDO)

    entries = [build_entry(r, obs_flags) for r in records]

    missing_tier_a = TIER_A_CODES - {e["morphology_code"] for e in entries}
    if missing_tier_a:
        print("ERROR: Tier A code(s) not present in the generated inventory: %s"
              % ", ".join(sorted(missing_tier_a)), file=sys.stderr)
        return 2

    from collections import Counter
    breakdown = Counter(e["iccc3_subgroup_id"] for e in entries)

    if args.check:
        print("usable entries: %d" % len(entries))
        for sub in sorted(breakdown):
            print("  %s: %d" % (sub, breakdown[sub]))
        print("Tier A annotated: %d" % len(TIER_A_CODES))
        print("Tier B templated: %d" % (len(entries) - len(TIER_A_CODES)))
        return 0

    out_path = Path(args.out)

    # Carry any tree that is already on disk. See the module docstring: this script
    # generates morphology_entries[], and a regeneration that quietly drops a tree
    # someone else authored is indistinguishable, in the file, from a clean rebuild.
    existing_trees = []
    if out_path.exists() and not args.reset_tree:
        try:
            existing_trees = json.loads(out_path.read_text(encoding="utf-8")).get(
                "decision_trees") or []
        except (json.JSONDecodeError, OSError) as exc:
            print("ERROR: %s exists but could not be read (%s). Refusing to overwrite it "
                  "— a tree may be in there. Fix the file, or pass --reset-tree if you "
                  "genuinely mean to discard it." % (out_path, exc), file=sys.stderr)
            return 2
    if args.reset_tree and out_path.exists():
        print("--reset-tree: discarding the decision_trees[] currently on disk",
              file=sys.stderr)

    n_nodes = sum(len(t.get("nodes") or []) for t in existing_trees)
    tree_ids = [t.get("tree_id") for t in existing_trees if t.get("tree_id")]

    out = {
        "metadata": build_metadata(len(entries), payload["summary"], n_nodes, tree_ids),
        "morphology_entries": entries,
        "decision_trees": existing_trees,
    }
    out_path.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote %s (%d entries, %d tree(s) / %d node(s) carried across)"
          % (out_path, len(entries), len(existing_trees), n_nodes), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
