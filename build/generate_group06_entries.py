def obs_clause(preferred_is_obs: bool, any_other_obs: bool) -> str:
    if preferred_is_obs:
        return " -- this stem's own preferred term carries the ICD-O-3.2 [obs] marker"
    if any_other_obs:
        return (
            " (one or more synonym/related terms on this stem carry the ICD-O-3.2 "
            "[obs] marker; the preferred term itself does not)"
        )
    return ""


def load_obs_flags(icdo_path: Path) -> dict:
    """{(code4, behaviour): {'preferred': bool, 'other': bool}} from icdo32.sqlite."""
    import sqlite3

    con = sqlite3.connect("file:%s?mode=ro" % icdo_path, uri=True)
    con.row_factory = sqlite3.Row
    out: dict = {}
    for r in con.execute(
        "SELECT code4, behaviour, level, obs FROM icd_o_3_2_morphology "
        "WHERE code4 IS NOT NULL AND behaviour IS NOT NULL"
    ):
        key = (str(r["code4"]), str(r["behaviour"]))
        slot = out.setdefault(key, {"preferred": False, "other": False})
        if r["obs"]:
            if str(r["level"] or "").strip() == "Preferred":
                slot["preferred"] = True
            else:
                slot["other"] = True
    con.close()
    return out


def build_entry(rec: dict, obs_flags: dict) -> dict:
    code = rec["morphology_code"]
    behaviour = rec["behavior_code"]
    topo = rec["topography"]
    # Contract Step 3 / §0.2: C64.9-only codes get primary_sites ["C64.9"]; the
    # any-site codes take their constraint from the generator output, read not
    # guessed. House style uses a plain hyphen (matches groups 1-5), the generator
    # emits an en dash for the any-site range -- normalise it here, mechanically.
    if topo == ["C64.9"]:
        primary_sites = ["C64.9"]
    else:
        primary_sites = [t.replace("–", "-") for t in topo]

    flags = obs_flags.get((code, behaviour), {"preferred": False, "other": False})

    entry = {f: None for f in FIELD_ORDER}
    entry["morphology_code"] = code
    entry["morphology_name"] = rec["preferred_term"]
    entry["iccc3_subgroup_id"] = rec["iccc3_subgroup_id"]
    entry["iccc3_subgroup_name"] = rec["iccc3_subgroup_name"]
    # Contract Step 2: who_version is "WHO 2022" for every entry in this file --
    # Moch 2022 is the group's baseline paper (contract §0.4). Not conditional on
    # whether a current WHO entity is confirmed on the individual stem (contrast
    # Group 5's per-entry "WHO 2023" / "ICD-O-3.2" split) -- the contract states
    # this flatly and it is followed literally, including on 8959 (§0.7), where no
    # WHO 2022 entity in fact lives on the /3 behaviour; that absence is recorded
    # in the coding_note instead.
    entry["who_version"] = "WHO 2022"
    entry["behavior_code"] = behaviour
    entry["diagnostic_tests_required"] = ["Histology"]
    entry["ihc_markers_required"] = None
    entry["ihc_markers_exclude"] = None
    entry["imaging_sufficient"] = False
    entry["imaging_features"] = None
    entry["nos_fallback_code"] = None
    entry["nos_fallback_name"] = None
    # Ruling 9 (4 Sep 2026), enforced by build_database.py's check_no_clinical_alerts:
    # "this is a coding tool, not a clinical one" -- clinical_alert never carries text
    # in any of Groups 1-5, and a non-null value here is a hard FAIL. Left null on
    # every entry; see the 8963 and 8510 coding_notes for the conflict this creates
    # with the build contract's Step 3 instructions, and this file's build report.
    entry["clinical_alert"] = None
    entry["code_neutral_molecular"] = True
    entry["redcap_value"] = code
    entry["primary_sites"] = primary_sites
    entry["topography_dependent"] = False
    entry["topography_routing_note"] = None

    if code in TIER_A_ANNOTATIONS:
        entry.update(TIER_A_ANNOTATIONS[code])
    else:
        note = obs_clause(flags["preferred"], flags["other"])
        entry["coding_note"] = (
            GENERATED_NOTE + " ICD-O-3.2 preferred term %r, behaviour 3%s. One of "
            "the adult-type renal carcinomas in ICCC-3 subgroup %s (%s): reachable "
            "in the lookup tool only by direct code entry, with no decision-tree "
            "branch built to reach it -- Group 6's tree (authored by a later task) "
            "covers only the five paediatric-core codes and the small set of "
            "renal-carcinoma leaves the build contract names explicitly (contract "
            "§0.3); the remainder of the VIb carcinoma block, including this "
            "code, has no clerk-facing pathway of its own."
            % (rec["preferred_term"], note, rec["iccc3_subgroup_id"],
               rec["iccc3_subgroup_name"])
        ) + drift_note(code) + TIER_B_ADDENDA.get(code, "")

    return {f: entry[f] for f in FIELD_ORDER}


