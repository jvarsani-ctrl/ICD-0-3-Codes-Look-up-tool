def note(*parts: str) -> str:
    return " ".join(p.strip() for p in parts if p)


def key(code: str, behaviour: str) -> str:
    return "%s/%s" % (code, behaviour)


# --------------------------------------------------------------------------------------
# Topography. ICCC-2017 stores topography as three-digit codes (C62.0 -> 620); the
# inventory carries each range as a display string ("C70.0–C72.9").
# --------------------------------------------------------------------------------------
def topo3(code: str) -> int:
    m = re.fullmatch(r"C(\d\d)\.(\d)", code.strip())
    if not m:
        raise ValueError("not a topography code: %r" % code)
    return int(m.group(1)) * 10 + int(m.group(2))


def covers(displays: list, number: int) -> bool:
    for d in displays:
        parts = [p for p in re.split(r"[–-]", d) if p.strip()]
        lo, hi = topo3(parts[0]), topo3(parts[-1])
        if lo <= number <= hi:
            return True
    return False


def lookup_codes() -> list:
    """Every code the front door can capture, plus the three T3 adds, in numeric order."""
    lookup = json.loads(LOOKUP_PATH.read_text(encoding="utf-8"))["topography_lookup"]
    codes = set(lookup) | set(LOOKUP_ADDITIONS)
    return sorted(codes, key=topo3)


def subgroups_of(recs: list) -> dict:
    """{subgroup_id: {"name": ..., "topography": [display, ...]}} in subgroup-id order."""
    out: dict = {}
    for r in recs:
        sub = out.setdefault(r["iccc3_subgroup_id"],
                             {"name": r["iccc3_subgroup_name"], "topography": []})
        if sub["name"] != r["iccc3_subgroup_name"]:
            raise SystemExit("ERROR: subgroup %s carries two names for %s/%s"
                             % (r["iccc3_subgroup_id"], r["morphology_code"],
                                r["behavior_code"]))
        for t in r["topography"]:
            if t not in sub["topography"]:
                sub["topography"].append(t)
    return dict(sorted(out.items()))


def default_subgroup(subs: dict) -> str:
    if len(subs) == 1:
        return next(iter(subs))
    families = {}
    for sid in subs:
        family = sid[:2]
        if family not in DEFAULT_ORDER or family in families:
            raise SystemExit("ERROR: subgroups %s are not one per Xa/Xb/Xc family"
                             % ", ".join(subs))
        families[family] = sid
    for family in DEFAULT_ORDER:
        if family in families:
            return families[family]
    raise SystemExit("ERROR: no default subgroup among %s" % ", ".join(subs))


def routing(subs: dict, default: str, codes: list) -> tuple:
    """(rules, note) for a pair that ICCC-2017 places in more than one subgroup."""
    rules = []
    for sid, sub in subs.items():
        if sid == default:
            continue
        listed = [c for c in codes if covers(sub["topography"], topo3(c))]
        if not listed:
            raise SystemExit("ERROR: subgroup %s covers no code in the topography lookup" % sid)
        rules.append({"topography_in": listed, "iccc3_subgroup_id": sid,
                      "iccc3_subgroup_name": sub["name"]})
    where = "; ".join("%s at %s" % (sid, ", ".join(t.replace("–", "-")
                                                  for t in sub["topography"]))
                      for sid, sub in subs.items())
    others = " and ".join(r["iccc3_subgroup_id"] for r in rules)
    text = ("ICCC-2017 places this (code, behaviour) in %d subgroups by site: %s. The entry's "
            "own subgroup, %s, is the default (design D20): it shows when no topography was "
            "captured and at its own sites. The ordered rules override it to %s when the "
            "captured topography is one of the listed codes."
            % (len(subs), where, default, others))
    return rules, text


