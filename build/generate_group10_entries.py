def load_obs(icdo_path: Path) -> dict:
    """{(code, behaviour): [level, ...]} for the terms ICD-O-3.2 marks [obs]."""
    index, err = bd.load_icdo32(icdo_path.parent.parent)
    if err:
        raise GenerationError(err)
    return {k: [level for level, obs in terms.values() if obs]
            for k, terms in index.items()
            if any(obs for _, obs in terms.values())}


def emitted_by(code: str, behaviour: str, pairs_by_tree: dict) -> list:
    return [t for t, plist in pairs_by_tree.items() if key(code, behaviour) in plist]


def check_ihc_overrides(markers_by_pair: dict) -> None:
    """Every pair a checklist rule emits requires Histology and IHC and lists exactly the
    markers of the rules that emit it; no other pair claims IHC or ihc_markers_required."""
    problems = []
    for k, d in DECISIONS.items():
        over = d[2] if len(d) > 2 else {}
        bad = set(over) - set(OVERRIDABLE)
        if bad:
            problems.append("%s overrides %s, which is not overridable"
                            % (k, ", ".join(sorted(bad))))
        if k in markers_by_pair:
            if over.get("diagnostic_tests_required") != HIST_IHC:
                problems.append("%s is emitted by a stain panel rule but does not require "
                                "Histology and IHC" % k)
            if over.get("ihc_markers_required") != markers_by_pair[k]:
                problems.append("%s ihc_markers_required is %r; the rules that emit it "
                                "read %r" % (k, over.get("ihc_markers_required"),
                                             markers_by_pair[k]))
        else:
            if "ihc_markers_required" in over:
                problems.append("%s lists ihc_markers_required but no stain panel rule emits "
                                "it" % k)
            if "IHC" in (over.get("diagnostic_tests_required") or []):
                problems.append("%s requires IHC but no stain panel rule emits it" % k)
    missing = sorted(set(markers_by_pair) - set(DECISIONS))
    if missing:
        problems.append("stain panel rule(s) emit %s, which DECISIONS does not annotate"
                        % ", ".join(missing))
    if problems:
        raise GenerationError("; ".join(problems))


def join_and(items: list) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def build_entry(recs: list, obs: dict, codes: list, pairs_by_tree: dict, entering: set,
                germ_cell_sites: list) -> dict:
    first = recs[0]
    code, beh = first["morphology_code"], first["behavior_code"]
    name = first["preferred_term"]
    if not name:
        raise GenerationError("%s has no Preferred term in icdo32.sqlite" % key(code, beh))
    subs = subgroups_of(recs)
    default = default_subgroup(subs)

    sites = []
    for sub in subs.values():
        for t in sub["topography"]:
            t = t.replace("–", "-")
            if t not in sites:
                sites.append(t)

    e = {f: None for f in FIELD_ORDER}
    e.update({
        "morphology_code": code,
        "morphology_name": name,
        "iccc3_subgroup_id": default,
        "iccc3_subgroup_name": subs[default]["name"],
        "who_version": "ICD-O-3.2",
        "behavior_code": beh,
        "diagnostic_tests_required": list(HISTOLOGY),
        "imaging_sufficient": False,
        "clinical_alert": None,
        "code_neutral_molecular": True,
        "redcap_value": code,
        "primary_sites": sites,
        "topography_dependent": False,
    })
    rules = None
    if len(subs) > 1:
        rules, e["topography_routing_note"] = routing(subs, default, codes, entering,
                                                      germ_cell_sites)
        e["topography_dependent"] = True

    k = key(code, beh)
    trees = emitted_by(code, beh, pairs_by_tree)
    if k in DECISIONS:
        refs, sentence = DECISIONS[k][:2]
        if len(DECISIONS[k]) > 2:
            e.update(copy.deepcopy(DECISIONS[k][2]))
        e["coding_note"] = note(
            GENERATED_NOTE,
            "ICD-O-3.2 preferred term at /%s is %r." % (beh, name),
            sentence,
            "Emitted by %s (design %s)." % (join_and(trees), refs))
    elif k in OFF_TREE_SPECIAL:
        e["coding_note"] = note(GENERATED_NOTE, OFF_TREE_SPECIAL[k])
    else:
        obs_levels = obs.get((code, beh))
        e["coding_note"] = note(
            GENERATED_NOTE,
            "ICD-O-3.2 preferred term %r, behaviour %s%s." % (
                name, beh,
                " (%s term(s) on the stem carry [obs])" % ", ".join(obs_levels)
                if obs_levels else ""),
            OFF_TREE_NOTE)

    # Group 3's 9380 entry puts the rule list straight after topography_routing_note.
    if rules is not None:
        e["iccc3_subgroup_by_topography"] = rules

    return e


def build_entries(payload: dict, obs: dict, codes: list, trees: list) -> list:
    records = payload["records"]
    if len(records) != EXPECTED_RECORDS:
        raise GenerationError("the inventory holds %d (code, behaviour) records, the "
                         "contract expects %d" % (len(records), EXPECTED_RECORDS))
    grouped: dict = defaultdict(list)
    for r in records:
        grouped[(r["morphology_code"], r["behavior_code"])].append(r)
    if len(grouped) != EXPECTED_ENTRIES:
        raise GenerationError("the records collapse to %d (code, behaviour) pairs, the "
                         "contract expects %d" % (len(grouped), EXPECTED_ENTRIES))

    inventory = {key(c, b) for c, b in grouped}
    annotated = set(DECISIONS) | set(OFF_TREE_SPECIAL)
    pairs_by_tree = tree_pairs(trees)
    emitted = {p for plist in pairs_by_tree.values() for p in plist}
    problems = []
    if emitted - inventory:
        problems.append("a tree names pair(s) outside the inventory: %s"
                        % ", ".join(sorted(emitted - inventory)))
    if annotated - inventory:
        problems.append("annotated pair(s) absent from the inventory: %s"
                        % ", ".join(sorted(annotated - inventory)))
    if emitted - set(DECISIONS):
        problems.append("emitted pair(s) with no DECISIONS entry: %s"
                        % ", ".join(sorted(emitted - set(DECISIONS))))
    if set(DECISIONS) - emitted:
        problems.append("DECISIONS entry for pair(s) no tree emits: %s"
                        % ", ".join(sorted(set(DECISIONS) - emitted)))
    if problems:
        raise GenerationError("; ".join(problems))
    check_ihc_overrides(checklist_markers(trees))

    # The germ cell site ranges: Xa, Xb and Xc. Xd and Xe ranges 114 and 116 run C00.0-C80.9.
    germ_cell_sites = sorted({t for r in records if r["iccc3_subgroup_id"][:2] in DEFAULT_ORDER
                              for t in r["topography"]})
    entering = entering_codes()
    return [build_entry(grouped[k], obs, codes, pairs_by_tree, entering, germ_cell_sites)
            for k in sorted(grouped)]


def build_metadata(entries: list, summary: dict, trees: list) -> dict:
    n_nodes = sum(len(t.get("nodes") or []) for t in trees)
    shared = sum(1 for e in entries if e["topography_dependent"])
    return {
        "group_id": GROUP,
        "group_name": "Germ Cell, Trophoblastic Tumors and Neoplasms of Gonads",
        "iccc3_version": "3rd edition",
        "icdo_version": (
            "ICD-O-3.2. morphology_entries[] is GENERATED by build/generate_group10_entries.py"
            " from ICCC-2017.sqlite joined to icdo32.sqlite (contract §2). Generator summary:"
            " ICCC range entries %d, distinct codes %d, absent from ICD-O-3.2 at a declared"
            " behaviour %d, usable %d, (code,behaviour) records %d, grouped by (code,"
            " behaviour) into %d entries. %d of those pairs sit in more than one subgroup by"
            " site and carry iccc3_subgroup_by_topography (design D16)."
            % (summary["iccc_code_range_entries"], summary["iccc_distinct_codes"],
               len(summary["codes_absent_from_icdo32"]), summary["usable_distinct_codes"],
               summary["morphology_entry_records"], len(entries), shared)
        ),
        "total_morphology_entries": len(entries),
        "total_decision_nodes": n_nodes,
        "decision_trees": [t["tree_id"] for t in trees],
        "basis_of_diagnosis_declarations": dict(bd.BASIS_DECLARED_GAPS),
    }


def report(entries: list) -> None:
    print("entries: %d · topography-dependent: %d"
          % (len(entries), sum(1 for e in entries if e["topography_dependent"])))


def main(argv=None) -> int:
    try:
        return run(argv)
    except GenerationError as exc:
        print("ERROR: %s" % exc, file=sys.stderr)
        return 2


def run(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 when the file on disk would change")
    ap.add_argument("--out", default=str(OUT_PATH))
    args = ap.parse_args(argv)

    try:
        trees = group10_tree.trees()
    except group10_tree.TreeError as exc:
        raise GenerationError(str(exc)) from None
    payload = gi.build_inventory(ICCC_PATH, ICDO_PATH, ICCC_GROUP)
    entries = build_entries(payload, load_obs(ICDO_PATH), lookup_codes(), trees)

    out_path = Path(args.out)
    existing = None
    if out_path.exists():
        try:
            text = out_path.read_text(encoding="utf-8")
            carry_branch_sequences(trees, json.loads(text).get("decision_trees"))
            existing = text
        except (json.JSONDecodeError, OSError) as exc:
            print("ERROR: %s exists but could not be read (%s); refusing to overwrite it"
                  % (out_path, exc), file=sys.stderr)
            return 2
    doc = {
        "metadata": build_metadata(entries, payload["summary"], trees),
        "morphology_entries": entries,
        "decision_trees": trees,
    }
    text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"

    if args.check:
        report(entries)
        if existing == text:
            print("%s is up to date" % out_path)
            return 0
        print("%s would change" % out_path, file=sys.stderr)
        return 1

    out_path.write_text(text, encoding="utf-8")
    print("wrote %s (%d entries, %d node(s))"
          % (out_path, len(entries), doc["metadata"]["total_decision_nodes"]), file=sys.stderr)
    report(entries)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
