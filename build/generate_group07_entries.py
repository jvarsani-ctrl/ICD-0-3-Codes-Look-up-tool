def load_redcap_group7() -> dict:
    """{code: [option names]} for Group 7, read with build_database's own parser."""
    import build_database as bd  # noqa: E402

    options, _ = bd.parse_redcap_options(LAYER1)
    return {code: rec.get("names") or [rec["name"]] for code, rec in (options.get(7) or {}).items()}


def load_obs(icdo_path: Path) -> dict:
    import sqlite3

    con = sqlite3.connect("file:%s?mode=ro" % icdo_path, uri=True)
    out: dict = {}
    for code4, beh, level, obs in con.execute(
            "SELECT code4, behaviour, level, obs FROM icd_o_3_2_morphology "
            "WHERE code4 IS NOT NULL AND behaviour IS NOT NULL"):
        if obs:
            slot = out.setdefault((str(code4), str(beh)), set())
            slot.add("preferred" if str(level).strip() == "Preferred" else "other")
    con.close()
    return out


# The ICCC-2017.sqlite row behind each Group VII subgroup (contract §0.2). VIIb holds two
# rows: 71 for the any-site codes 8160-8162 and 8170-8180, 70 for the C22 carcinoma block.
ICCC_ROW_BY_SUBGROUP = {"VIIa1": "67", "VIIa2": "68", "VIIa3": "69", "VIIb": "70", "VIIc": "72"}
ANY_SITE_VIIB = {"8160", "8161", "8162"} | {str(c) for c in range(8170, 8181)}


def iccc_range_row(code: str, subgroup: str) -> str:
    if subgroup == "VIIb" and code in ANY_SITE_VIIB:
        return "71"
    return ICCC_ROW_BY_SUBGROUP.get(subgroup, "?")


def build_entry(rec: dict, redcap: dict, obs: dict) -> dict:
    code, behaviour = rec["morphology_code"], rec["behavior_code"]
    topo = [t.replace("–", "-") for t in rec["topography"]]

    entry = {f: None for f in FIELD_ORDER}
    entry.update(
        morphology_code=code,
        morphology_name=rec["preferred_term"],
        iccc3_subgroup_id=rec["iccc3_subgroup_id"],
        iccc3_subgroup_name=rec["iccc3_subgroup_name"],
        who_version="ICD-O-3.2",
        behavior_code=behaviour,
        diagnostic_tests_required=["Histology"],
        imaging_sufficient=False,
        clinical_alert=None,                       # ruling 9; check_no_clinical_alerts()
        code_neutral_molecular=True,
        redcap_value=code,
        primary_sites=topo,
        topography_dependent=False,
        topography_routing_note="",
    )
    ann = ANNOTATIONS.get(code)
    if ann:
        entry.update(ann)
    if not entry.get("coding_note"):
        flags = obs.get((code, behaviour), set())
        obs_clause = ""
        if "preferred" in flags:
            obs_clause = "; the preferred term itself carries the ICD-O-3.2 [obs] marker"
        elif flags:
            obs_clause = "; a synonym or related term on this code carries [obs]"
        entry["coding_note"] = (
            GENERATED_NOTE + " ICD-O-3.2 preferred term %r, behaviour 3%s."
            % (rec["preferred_term"], obs_clause)
            + TIER_B_NOTE % (rec["iccc3_subgroup_id"], rec["iccc3_subgroup_name"])
        )
    if code == "8171":
        entry["code_neutral_molecular"] = False     # contract §3.2: a negative test can move it

    out = {f: entry[f] for f in FIELD_ORDER}
    names = redcap.get(code)
    if names is None:
        out["redcap_option_verified"] = False
        out["awaiting_layer1"] = {
            "reason": (
                "ICD-O-3.2 code %s/3 '%s', verified against icdo32.sqlite and inside ICCC-2017 "
                "range %s, is not an option in RedCap Options/Group 7- Hepatic Tumors.md. "
                "Built under registrar rulings 1-3 of 4 September 2026 (contract §2B)."
                % (code, rec["preferred_term"], iccc_range_row(code, rec["iccc3_subgroup_id"]))
            ),
            "needs": ["REDCap Group 7 option list"],
            "todo": "docs/codes-awaiting-redcap.md",
        }
    else:
        out["redcap_option_verified"] = rec["preferred_term"] in names
    return out


